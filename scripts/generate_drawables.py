#!/usr/bin/env python3
"""Generate the widget's vector drawables.

1. State shapes (M3 Expressive-style scalloped shapes), one per thread state.
2. A bundled subset of Lucide icons (stroke icons) for projects whose T3 Code icon is Lucide,
   plus the Kotlin lookup table `LucideIcons.kt`.

Usage: generate_drawables.py <lucide-svg-dir>
Download the SVGs from the `lucide-static` npm package (icons/<name>.svg). Lucide is ISC-licensed.
"""
import math
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"
KOTLIN = ROOT / "app/src/main/java/app/t3widget/widget/LucideIcons.kt"

# name: (lobes, amplitude). Each state gets a distinct silhouette.
SHAPES = {
    "shape_needs_you": (12, 0.12),  # burst
    "shape_running": (9, 0.08),     # cookie
    "shape_done": (4, 0.16),        # clover
    "shape_failed": (6, 0.14),      # flower
    "shape_waiting": (5, 0.10),     # soft pentagon
}


def scallop(lobes: int, amp: float) -> str:
    pts = []
    for i in range(0, 360, 2):
        a = math.radians(i)
        r = 46 * (1 + amp * math.cos(lobes * a)) / (1 + amp)
        pts.append(f"{50 + r * math.cos(a):.2f},{50 + r * math.sin(a):.2f}")
    return "M" + " L".join(pts) + " Z"


def shape_xml(path: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_drawables.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp" android:height="48dp"
    android:viewportWidth="100" android:viewportHeight="100">
    <path android:fillColor="#FFFFFFFF" android:pathData="{path}" />
</vector>
"""


def f(el, k, default="0"):
    return float(el.get(k, default))


def element_to_path(el) -> str | None:
    tag = el.tag.split("}")[-1]
    if tag == "path":
        return el.get("d")
    if tag == "circle":
        cx, cy, r = f(el, "cx"), f(el, "cy"), f(el, "r")
        return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0"
    if tag == "ellipse":
        cx, cy, rx, ry = f(el, "cx"), f(el, "cy"), f(el, "rx"), f(el, "ry")
        return f"M{cx - rx},{cy} a{rx},{ry} 0 1,0 {2 * rx},0 a{rx},{ry} 0 1,0 {-2 * rx},0"
    if tag == "line":
        return f"M{f(el, 'x1')},{f(el, 'y1')} L{f(el, 'x2')},{f(el, 'y2')}"
    if tag in ("polyline", "polygon"):
        nums = re.findall(r"-?[\d.]+", el.get("points", ""))
        pts = [f"{nums[i]},{nums[i + 1]}" for i in range(0, len(nums) - 1, 2)]
        return "M" + " L".join(pts) + (" Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y, w, h = f(el, "x"), f(el, "y"), f(el, "width"), f(el, "height")
        rx = float(el.get("rx", el.get("ry", "0")))
        ry = float(el.get("ry", el.get("rx", "0")))
        if rx == 0:
            return f"M{x},{y} h{w} v{h} h{-w} Z"
        return (
            f"M{x + rx},{y} h{w - 2 * rx} a{rx},{ry} 0 0 1 {rx},{ry} v{h - 2 * ry} "
            f"a{rx},{ry} 0 0 1 {-rx},{ry} h{-(w - 2 * rx)} a{rx},{ry} 0 0 1 {-rx},{-ry} "
            f"v{-(h - 2 * ry)} a{rx},{ry} 0 0 1 {rx},{-ry} Z"
        )
    return None


def lucide_xml(svg_path: pathlib.Path) -> str:
    root = ET.parse(svg_path).getroot()
    paths = [p for el in root.iter() if (p := element_to_path(el))]
    body = "\n".join(
        f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="2" '
        f'android:strokeLineCap="round" android:strokeLineJoin="round" '
        f'android:fillColor="#00000000" android:pathData="{p}" />'
        for p in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_drawables.py from Lucide ({svg_path.stem}), ISC license -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="24" android:viewportHeight="24">
{body}
</vector>
"""


def main() -> None:
    RES.mkdir(parents=True, exist_ok=True)
    for name, (lobes, amp) in SHAPES.items():
        (RES / f"{name}.xml").write_text(shape_xml(scallop(lobes, amp)))

    names = []
    for svg in sorted(pathlib.Path(sys.argv[1]).glob("*.svg")):
        res = "lucide_" + svg.stem.replace("-", "_")
        (RES / f"{res}.xml").write_text(lucide_xml(svg))
        names.append((svg.stem, res))

    entries = "\n".join(f'        "{n}" to R.drawable.{r},' for n, r in names)
    KOTLIN.write_text(f"""package app.t3widget.widget

import app.t3widget.R

/** Generated by scripts/generate_drawables.py. Lucide icons we bundle; others fall back to a monogram. */
object LucideIcons {{
    val byName: Map<String, Int> = mapOf(
{entries}
    )
}}
""")
    print(f"{len(SHAPES)} shapes, {len(names)} lucide icons")


if __name__ == "__main__":
    main()
